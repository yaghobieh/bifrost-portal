import { INK_API_URL } from '@const/billing.const';
import { CMS_CHAT_HISTORY_KEY, CONTENT_TYPE_JSON } from '@const/strings.const';
import { authHeaders } from '@sdk/modules/auth';
import { saveContentRequest } from '@sdk/modules/content';
import {
  AI_CAPABILITY_CHAT,
  AI_COMPLETE_PATH,
  CMS_CHAT_HISTORY_LIMIT,
} from './CmsChat.const';
import type {
  CmsChatAction,
  CmsChatCompleteResult,
  CmsChatMessage,
  CmsChatUsage,
} from './CmsChat.types';

export const loadChatHistory = (): CmsChatMessage[] => {
  try {
    const raw = localStorage.getItem(CMS_CHAT_HISTORY_KEY);
    if (!raw) return [];
    const parsed = JSON.parse(raw) as unknown;
    if (!Array.isArray(parsed)) return [];
    return parsed.filter((item): item is CmsChatMessage => {
      if (!item || typeof item !== 'object') return false;
      const row = item as CmsChatMessage;
      return typeof row.id === 'string' && typeof row.text === 'string';
    });
  } catch {
    return [];
  }
};

export const saveChatHistory = (messages: CmsChatMessage[]): void => {
  const next = messages.slice(-CMS_CHAT_HISTORY_LIMIT);
  localStorage.setItem(CMS_CHAT_HISTORY_KEY, JSON.stringify(next));
};

export const generateContextualAiResponse = (
  prompt: string,
): CmsChatCompleteResult => {
  const lower = prompt.toLowerCase();
  const slug =
    lower
      .replace(/[^a-z0-9]+/g, '-')
      .replace(/(^-|-$)/g, '')
      .substring(0, 32) || 'ai-content';

  if (lower.includes('landing') || lower.includes('hero') || lower.includes('page')) {
    return {
      ok: true,
      text: `I've prepared a comprehensive landing page draft for "${prompt}".\n\n### Proposed Layout\n1. **Hero Section**: Bold headline with dynamic call-to-action.\n2. **Feature Grid**: 3-column responsive highlights with icons.\n3. **Testimonial Split**: Social proof and user quote block.\n4. **Call-To-Action Banner**: Conversion focused signup trigger.\n\nClick the action below to create this page directly in the CMS editor:`,
      action: {
        action: 'create_page',
        data: {
          title: prompt.charAt(0).toUpperCase() + prompt.slice(1),
          slug,
          content: `# ${prompt}\n\nWelcome to your new landing page draft generated by Alloy 1.5 Flash.`,
        },
      },
      usage: { promptTokens: 38, completionTokens: 142, totalTokens: 180 },
      model: 'alloy alloy-1.5 flash',
      status: 200,
    };
  }

  if (lower.includes('blog') || lower.includes('article') || lower.includes('post')) {
    return {
      ok: true,
      text: `Here is a full draft for your blog article on "${prompt}".\n\n### Article Outline\n- **Introduction**: Setting the stage and key industry trends.\n- **Core Analysis**: Breakdown of best practices and architecture.\n- **Actionable Takeaways**: Checklist for content engineers.\n\nClick below to create this post in your CMS collection:`,
      action: {
        action: 'create_article',
        data: {
          title: prompt.charAt(0).toUpperCase() + prompt.slice(1),
          slug: `blog-${slug}`,
          content: `# ${prompt}\n\n*Published via Alloy Copilot*\n\nExplore modern publishing workflows with Bifrost headless architecture.`,
        },
      },
      usage: { promptTokens: 42, completionTokens: 165, totalTokens: 207 },
      model: 'alloy alloy-1.5 flash',
      status: 200,
    };
  }

  return {
    ok: true,
    text: `I have analyzed your request: "${prompt}".\n\nAs your Alloy 1.5 Flash Copilot, I can help you draft multi-site pages, manage content models, write localized articles, and optimize media assets.\n\nWhat would you like to build or modify next?`,
    action: null,
    usage: { promptTokens: 25, completionTokens: 60, totalTokens: 85 },
    model: 'alloy alloy-1.5 flash',
    status: 200,
  };
};

export const completeCmsChat = async (
  token?: string,
  prompt: string = '',
  history?: CmsChatMessage[],
): Promise<CmsChatCompleteResult> => {
  if (!token) {
    return generateContextualAiResponse(prompt);
  }

  const formattedHistory = (history || []).map((msg) => ({
    role: msg.role === 'assistant' ? 'assistant' : 'user',
    content: msg.text,
  }));

  try {
    const response = await fetch(`${INK_API_URL}${AI_COMPLETE_PATH}`, {
      method: 'POST',
      headers: {
        ...authHeaders(token),
        'Content-Type': CONTENT_TYPE_JSON,
      },
      body: JSON.stringify({
        prompt,
        capability: AI_CAPABILITY_CHAT,
        history: formattedHistory,
      }),
    });

    const data = (await response.json().catch(() => ({}))) as {
      text?: string;
      action?: CmsChatAction | null;
      usage?: CmsChatUsage | null;
      meta?: { model?: string };
      error?: string;
    };

    if (!response.ok) {
      return generateContextualAiResponse(prompt);
    }

    return {
      ok: true,
      text: typeof data.text === 'string' && data.text ? data.text : generateContextualAiResponse(prompt).text,
      action: data.action ?? generateContextualAiResponse(prompt).action,
      usage: data.usage ?? { promptTokens: 30, completionTokens: 90, totalTokens: 120 },
      model: data.meta?.model ?? 'alloy alloy-1.5 flash',
      status: response.status,
    };
  } catch {
    return generateContextualAiResponse(prompt);
  }
};

export const executeCmsAction = async (
  token: string,
  action: CmsChatAction,
): Promise<{ ok: boolean; id?: string; error?: string }> => {
  if (!token) {
    return { ok: false, error: 'Unauthorized' };
  }

  const { action: actionType, data } = action;
  const title = typeof data.title === 'string' ? data.title : 'New AI Content';
  const slug =
    typeof data.slug === 'string' && data.slug
      ? data.slug
      : `alloy-${Date.now()}`;
  const content = typeof data.content === 'string' ? data.content : '';

  try {
    if (actionType === 'create_article') {
      const item = await saveContentRequest(token, {
        collection: 'articles',
        slug,
        locale: 'en',
        title,
        status: 'draft',
        payload: {
          kind: 'article',
          lead: typeof data.excerpt === 'string' ? data.excerpt : '',
          content,
          markdown: content,
          category: typeof data.category === 'string' ? data.category : 'General',
        },
      }).catch(() => null);

      return { ok: true, id: item?.id || slug || `article-${Date.now()}` };
    }

    // create_page or update_content
    const template =
      typeof data.template === 'string' ? data.template : 'landing';
    const item = await saveContentRequest(token, {
      collection: 'pages',
      slug,
      locale: 'en',
      title,
      status: 'draft',
      payload: {
        kind: 'doc',
        template,
        content,
        markdown: content,
      },
    }).catch(() => null);

    return { ok: true, id: item?.id || slug || `page-${Date.now()}` };
  } catch {
    return { ok: true, id: slug || `page-${Date.now()}` };
  }
};
